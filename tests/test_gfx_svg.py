    def test_single_source_interval_validation_is_linear(self):
        counts=[]
        for n in (2,4):
            c=self._publish_mock_frames(n)
            verify_input_identity(c)
            with gfx_svg.consumer_scope(c):
                with mock.patch.object(gfx_svg,'read_input',wraps=gfx_svg.read_input) as reads:
                    source=png_source(c,self.clip)
                    for i in range(n): source.require_ready(i,i+1)
                    counts.append(reads.call_count)
