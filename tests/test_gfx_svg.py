    def _preview_mock(self,c,*,mutate=False):
        calls=[]
        def run(argv,need=True):
            target=Path(argv[-1]); target.parent.mkdir(parents=True,exist_ok=True); target.write_bytes(b'ordinary fake FFmpeg output')
            calls.append(argv)
            if mutate and len(calls)==1:
                (self.root/'generator.js').write_text('// changed during preview')
            return SimpleNamespace(returncode=0,stdout='',stderr='')
        return run,calls

    def test_preview_operation_uses_scoped_svg_snapshot(self):
        from vtx import subs, composite, frame_source
        counts=[]
        for n in (2,4):
            c=self._publish_mock_frames(n); c.gpu=False
            run,calls=self._preview_mock(c)
            with mock.patch.object(c,'run',side_effect=run), \
                 mock.patch.object(subs,'seg_encoder_kind',return_value='x264'), \
                 mock.patch.object(composite,'pick_vcodec',return_value=(['-c:v','libx264'],'x264')), \
                 mock.patch.object(gfx_svg,'read_input',wraps=gfx_svg.read_input) as reads, \
                 mock.patch.object(frame_source,'png_invalid_reason',wraps=frame_source.png_invalid_reason) as pngs:
                subs.run_preview(c,[f'f{i}' for i in range(n)],dry=False)
                counts.append((reads.call_count,pngs.call_count,len(calls)))
            self.assertFalse(hasattr(c,'_svg_consumer_sources'))
        self.assertEqual(counts,[(16,4,6),(26,8,12)])  # 3(N+2)+2N, with generator
        print('SVG_ACTUAL_PREVIEW_COUNTS',counts)
        c=self._publish_mock_frames(2)
        for failure in (RuntimeError('ordinary failure'), KeyboardInterrupt()):
            with mock.patch.object(subs,'_run_preview',side_effect=failure), self.assertRaises(type(failure)):
                subs.run_preview(c,['f0'],dry=False)
            self.assertFalse(hasattr(c,'_svg_consumer_sources'))

