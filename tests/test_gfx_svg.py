    def test_preview_svg_cache_failure_cannot_print_pass(self):
        from vtx import subs, composite, frame_source
        for change in ('pixels','truncated','marker','missing'):
            c=self._publish_mock_frames(2); c.gpu=False; source=png_source(c,self.clip)
            run,calls=self._preview_mock(c); output=io.StringIO()
            def changed_run(argv,need=True):
                result=run(argv,need)
                if len(calls)==1:
                    if change=='pixels': write_png(source.frame_path(1),1920,1080,frame=8)
                    elif change=='truncated': source.frame_path(1).write_bytes(b'ordinary truncated PNG')
                    elif change=='marker': (source.directory/gfx_svg.COMPLETE_FILE).write_text('{}')
                return result
            original_png_check=frame_source.png_invalid_reason
            def png_check(path,**kwargs):
                if change=='missing' and calls and path==source.frame_path(1):
                    return 'ordinary mock missing PNG'
                return original_png_check(path,**kwargs)
            with self.subTest(change=change), mock.patch.object(c,'run',side_effect=changed_run), \
                 mock.patch.object(frame_source,'png_invalid_reason',side_effect=png_check), \
                 mock.patch.object(subs,'seg_encoder_kind',return_value='x264'), \
                 mock.patch.object(composite,'pick_vcodec',return_value=(['-c:v','libx264'],'x264')), \
                 contextlib.redirect_stdout(output), self.assertRaises(ValueError):
                subs.run_preview(c,['f0','f1'],dry=False)
