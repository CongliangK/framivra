REAL_ENGINE_IDENTITY = gfx_svg.engine_identity

ENGINE = {'name': 'inkscape', 'version': 'Inkscape test', 'executable': '/test/inkscape', 'sha256': 'e' * 64}
SVG = '<svg xmlns="http://www.w3.org/2000/svg" width="1920" height="1080" viewBox="0 0 1920 1080"><rect width="100" height="100" fill="red"/></svg>'


class SvgContract(unittest.TestCase):
    def setUp(self):
        self.root = temporary_root(self)
        self.engine = mock.patch.object(gfx_svg, 'engine_identity', return_value=ENGINE)
        self.engine.start(); self.addCleanup(self.engine.stop)
        for method, value in [('fontconfig_identity', {'executable': '/test/fc-scan', 'version': 'fontconfig test', 'sha256': 'f'*64}),
                              ('_font_faces', [{'family': 'test', 'style': 'Regular', 'index': 0}])]:
            patch = mock.patch.object(gfx_svg, method, return_value=value)
            patch.start(); self.addCleanup(patch.stop)
        self.clip = dict(format='svg-sequence', src='manifest.json', dst_in=9, dur=2)
        self.manifest = dict(format=gfx_svg.FORMAT, fps=30, width=1920, height=1080,
                             frame_count=2, frames=['f0.svg', 'f1.svg'], generator='generator.js')
        self.timeline = dict(version=2, project=dict(fps=30, width=1920, height=1080, duration_frames=12),
            sources=[], video_tracks=[dict(name='graphics', kind='gfx', clips=[self.clip])], subtitles=[], audio_tracks=[])
        for name in self.manifest['frames']:
            (self.root / name).write_text(SVG)
        (self.root / 'generator.js').write_text('// pre-generated by an external tool')
        self.save()

    def save(self):
        (self.root / 'manifest.json').write_text(json.dumps(self.manifest))
        (self.root / 'timeline.json').write_text(json.dumps(self.timeline))

    def ctx(self):
        return Ctx(self.root / 'timeline.json')

    def test_explicit_route_never_calls_html_identity(self):
        with mock.patch('vtx.render.gfx_dependencies.resolve', side_effect=AssertionError('HTML resolver invoked')), \
             mock.patch('vtx.render.gfx_environment.identity', side_effect=AssertionError('browser environment invoked')), \
             mock.patch('vtx.render.gfx_environment.recheck', side_effect=AssertionError('browser recheck invoked')):
            c = self.ctx()
            self.assertEqual(c.gfx_backend['requested_backend'], 'svg-sequence')
            self.assertEqual(gfx_svg.route(c), 'svg-sequence')
            self.assertIn(gfx_svg.NAMESPACE, str(gfx_dir(c, self.clip)))
            verify_input_identity(c)

    def test_manifest_count_canvas_rate_and_local_frames(self):
        for field, value in [('frame_count', 1), ('width', 1280), ('height', 720), ('fps', 24), ('frames', ['f0.svg'])]:
            old = copy.deepcopy(self.manifest)
            self.manifest[field] = value; self.save()
            with self.assertRaises(ValueError): self.ctx()
            self.manifest = old
        self.save()
        c = self.ctx(); record = gfx_svg.resolve(c, self.clip)
        self.assertEqual(record['frames'], ['f0.svg', 'f1.svg'])
        self.assertEqual(record['frame_count'], self.clip['dur'])

    def test_manifest_generator_frame_and_dependency_changes_invalidate(self):
        (self.root / 'dependency.txt').write_text('one')
        self.clip['cache_dependencies'] = ['dependency.txt']; self.save()
        for name in ['generator.js', 'dependency.txt', 'f0.svg']:
            c = self.ctx(); key = gfx_key(c, self.clip)
            p = self.root / name; original = p.read_text()
            p.write_text(original.replace('red', 'blue') if name.endswith('.svg') else original + ' changed')
            self.assertNotEqual(key, gfx_key(c, self.clip))
            with self.assertRaises(InputIdentityError): verify_input_identity(c)
            p.write_text(original)
        c = self.ctx(); old = gfx_key(c, self.clip)
        self.manifest['_meta'] = 'changed'; self.save()
        self.assertNotEqual(old, gfx_key(c, self.clip))

    def test_font_bytes_and_actual_engine_version_invalidate(self):
        self.manifest['fonts'] = ['font.ttf']
        (self.root / 'font.ttf').write_bytes(b'font-version-one'); self.save()
        c = self.ctx(); old = gfx_key(c, self.clip)
        (self.root / 'font.ttf').write_bytes(b'font-version-two')
        self.assertNotEqual(old, gfx_key(c, self.clip))
        old = gfx_key(c, self.clip)
        with mock.patch.object(gfx_svg, 'engine_identity', return_value={**ENGINE, 'version': 'Inkscape next'}):
            self.assertNotEqual(old, gfx_key(c, self.clip))

