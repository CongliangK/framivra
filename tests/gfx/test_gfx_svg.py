                    if first == second:
                        with self.assertRaisesRegex(ValueError, 'input changed during impact capture'):
                            capture(self.timeline, self.root)
                    else:
                        with self.assertRaises((OSError, ValueError)):
                            capture(self.timeline, self.root)

