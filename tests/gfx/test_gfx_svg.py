    def test_producer_completion_warm_reader_and_corruption(self):
        def render(executable, directory, count, width, height, *, root=None):
            for i in range(count): write_png(directory / f'f{i:04d}.png',width,height,frame=i)
        c = self.ctx()
        with mock.patch.object(gfx_svg_stage, 'run_shell', side_effect=render) as engine:
            gfx_svg_stage.render_stage(c)
            source = png_source(c,self.clip); source.require_ready()
            self.assertEqual(resolve_frames(c,self.clip),[source.frame_path(0),source.frame_path(1)])
            gfx_svg_stage.render_stage(c); self.assertEqual(engine.call_count,1)
            source.frame_path(1).write_bytes(b'broken')
            with self.assertRaises(ValueError): source.require_ready()
            gfx_svg_stage.render_stage(c); self.assertEqual(engine.call_count,2)
            source.require_ready()  # Outside scope, the regenerated completion is fully rechecked.
        marker=source.directory/gfx_svg.COMPLETE_FILE
        value=json.loads(marker.read_text()); value['input']['engine']['version']='false'
        marker.write_text(json.dumps(value))
        with self.assertRaises(ValueError): resolve_frames(c,self.clip)

