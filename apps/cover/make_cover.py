def cmd_all(args):
    w, h = parse_size(args.size)
    out = Path(args.out)
    if args.bg_src:
        cmd_prep_bg(argparse.Namespace(src=args.bg_src,
                                       out=str(out / f"bg_{w}x{h}.png"),
                                       size=f"{w}x{h}"))
    cmd_render(args)
    cmd_previews(argparse.Namespace(dir=str(out), cover=None))
    cmd_qc(argparse.Namespace(dir=str(out)))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--version", action="version",
                    version="make_cover.py · D50 · 收编自 voice-ime/cover (2026-09-13)")
    sub = ap.add_subparsers(dest="cmd", required=True)

    def canvas_opts(sp):
        sp.add_argument("--size", default=f"{CANVAS[0]}x{CANVAS[1]}", help="画布 WxH，默认 1920x1200（16:10）")

    def render_opts(sp, with_bg_src=False):
        sp.add_argument("--out", required=True, help="产物目录（如 <项目>/cover）")
        sp.add_argument("--bg", help="背景图路径（默认 <out>/bg_<W>x<H>.png）")
        if with_bg_src:
            sp.add_argument("--bg-src", help="imgen 原图（先走 prep-bg）；与 --bg 二选一")
        sp.add_argument("--title", required=True, help='大标题，空格分段：奇数段细体 55%%，如 "说话 就是 打字"')
        sp.add_argument("--sub", required=True, help="小字，如 'Linux 开源 · 语音键盘同引擎'")
        canvas_opts(sp)
        sp.add_argument("--title-top", type=int, default=TITLE_TOP)
        sp.add_argument("--title-size", type=int, default=TITLE_SIZE)
        sp.add_argument("--title-weight", type=int, default=TITLE_WEIGHT)
        sp.add_argument("--light-ratio", type=float, default=LIGHT_RATIO)
        sp.add_argument("--light-weight", type=int, default=LIGHT_WEIGHT)
        sp.add_argument("--gap", type=int, default=GAP)
        sp.add_argument("--sub-top", type=int, default=SUB_TOP)
        sp.add_argument("--sub-size", type=int, default=SUB_SIZE)
        sp.add_argument("--sub-weight", type=int, default=SUB_WEIGHT)
        sp.add_argument("--sub-ls", type=float, default=SUB_LS)
        sp.add_argument("--sub-alpha", type=float, default=SUB_ALPHA)
        sp.add_argument("--text-color", default=TEXT_COLOR)
        sp.add_argument("--font", default=FONT_STACK)
        sp.add_argument("--bg-fallback", default=BG_FALLBACK)
        sp.add_argument("--yavg-min", type=float, default=YAVG_MIN)
        sp.add_argument("--jpg-max-mb", type=float, default=JPG_MAX_MB)

    sp = sub.add_parser("prep-bg", help="原图 lanczos cover-crop 到精确画布")
    sp.add_argument("src")
    sp.add_argument("-o", "--out")
    canvas_opts(sp)

    sub.add_parser("render", help="生成 HTML + Chrome 截图 + PNG/JPG")\
        .set_defaults(func=None)  # 占位，下面统一注册
    sp = sub.choices["render"]
    render_opts(sp)

    sp = sub.add_parser("previews", help="四端裁切预览（pc_16x9/thumb_384/app_138/app_43）")
    sp.add_argument("--dir", default=".", help="封面目录（读 cover.meta.json 与 cover_*.png）")
    sp.add_argument("--cover", help="显式指定封面 PNG（默认 <dir>/cover_<W>x<H>.png）")

    sp = sub.add_parser("qc", help="验证门（尺寸/几何/YAVG/JPG 体积）")
    sp.add_argument("--dir", default=".", help="封面目录")

    sp = sub.add_parser("all", help="prep-bg(可选) → render → previews → qc 一条龙")
    render_opts(sp, with_bg_src=True)

    args = ap.parse_args()
    {"prep-bg": cmd_prep_bg, "render": cmd_render, "previews": cmd_previews,
     "qc": cmd_qc, "all": cmd_all}[args.cmd](args)


if __name__ == "__main__":
    main()
