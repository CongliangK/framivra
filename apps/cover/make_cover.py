def run(cmd, **kw):
    """跑外部命令；非零退出码直接抛异常（fail fast，不留半成品进产物目录）。"""
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        sys.stderr.write(r.stderr[-2000:] if r.stderr else f"命令失败: {cmd}\n")
        raise SystemExit(f"exit {r.returncode}: {' '.join(str(c) for c in cmd[:6])}…")
    return r


def probe(path):
    """ffprobe 读 (宽, 高)；无效图返回 (0, 0)。"""
    r = subprocess.run(
        ["ffprobe", "-v", "quiet", "-print_format", "json", "-show_streams", str(path)],
        capture_output=True, text=True)
    try:
        s = json.loads(r.stdout)["streams"][0]
        return int(s["width"]), int(s["height"])
    except Exception:
        return 0, 0


def parse_size(text):
    m = re.fullmatch(r"(\d+)[xX×](\d+)", text.strip())
    if not m:
        raise SystemExit(f"尺寸格式应为 WxH，如 1920x1200，收到: {text}")
    return int(m.group(1)), int(m.group(2))


def find_chrome():
    for name in ("google-chrome", "google-chrome-stable", "chromium-browser", "chromium"):
        p = shutil.which(name)
        if p:
            return p
    # 与 vtx 同名的兜底环境变量（见 video_tools README「浏览器」节）
    import os
    p = os.environ.get("VTX_CHROME")
    if p and Path(p).exists():
        return p
    raise SystemExit("未找到 Chrome/Chromium（PATH 与 VTX_CHROME 均未命中）")


def ffmpeg_crop_scale(src, dst, w, h, note=""):
    """cover 语义：等比 lanczos 完全覆盖 W×H → 中心 crop → rgb24 压平。源<目标时警告后照做。"""
    sw, sh = probe(src)
    if sw and sh and (sw < w or sh < h):
        factor = max(w / sw, h / sh) if sw and sh else 0
        print(f"  ⚠ 源图 {sw}x{sh} 小于目标 {w}x{h}，将 lanczos 放大 {factor:.3f}×（画质损失已标注）{note}")
    vf = (f"scale={w}:{h}:force_original_aspect_ratio=increase:flags=lanczos,"
          f"crop={w}:{h},format=rgb24")
    run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(src), "-vf", vf,
         "-frames:v", "1", str(dst)])
    pw, ph = probe(dst)
    if (pw, ph) != (w, h):
        dst.unlink(missing_ok=True)
        raise SystemExit(f"后处理产物尺寸 {pw}x{ph} ≠ 契约 {w}x{h}，已删除")


# ── prep-bg ───────────────────────────────────────────────────────────────────
def cmd_prep_bg(args):
    w, h = parse_size(args.size)
    src, dst = Path(args.src), Path(args.out) if args.out else Path(f"bg_{w}x{h}.png")
    dst.parent.mkdir(parents=True, exist_ok=True)
    ffmpeg_crop_scale(src, dst, w, h)
    print(f"✓ prep-bg: {dst} ({w}x{h}) ← {src}")


# ── render ────────────────────────────────────────────────────────────────────
def build_html(p, bg_name):
    """p=参数 dict；返回 (html 文本, meta dict)。"""
    w, h = p["canvas"]
    light_size = round(p["title_size"] * p["light_ratio"])
    title_bottom = p["title_top"] + round(p["title_size"] * 1.1)   # line-height 1.1
    sub_bottom = p["sub_top"] + round(p["sub_size"] * 1.2)         # line-height 1.2
    segs = p["title"].split()
    spans = "".join(
        f'<span class="{"mid" if i % 2 else "big"}">{html.escape(s)}</span>'
        for i, s in enumerate(segs))
    hex6 = p["text_color"].lstrip("#")
    r, g, b = int(hex6[0:2], 16), int(hex6[2:4], 16), int(hex6[4:6], 16)
    sub_color = f"rgba({r},{g},{b},{p['sub_alpha']})"
    meta = {
        "tool": "video_tools/apps/cover/make_cover.py", "decision": "D50",
        "canvas": list(p["canvas"]), "bg": bg_name,
        "title": p["title"], "sub": p["sub"],
        "title_top": p["title_top"], "title_size": p["title_size"],
        "title_weight": p["title_weight"], "light_ratio": p["light_ratio"],
        "light_weight": p["light_weight"], "gap": p["gap"],
        "sub_top": p["sub_top"], "sub_size": p["sub_size"],
        "sub_weight": p["sub_weight"], "sub_ls": p["sub_ls"], "sub_alpha": p["sub_alpha"],
        "text_color": p["text_color"], "font": p["font"],
        "title_bottom": title_bottom, "sub_bottom": sub_bottom,
        "yavg_min": p["yavg_min"], "jpg_max_mb": p["jpg_max_mb"],
    }
    t = dict(
        W=w, H=h, FALLBACK=p["bg_fallback"], BG=bg_name, FONT=p["font"],
        TITLE_TOP=p["title_top"], TITLE_BOTTOM=title_bottom,
        TITLE_V0=round(100 * p["title_top"] / h, 1), TITLE_V1=round(100 * title_bottom / h, 1),
        V0=int(SAFE["v_lo"] * 100), V1=int(SAFE["v_hi"] * 100),
        GAP=p["gap"], COLOR=p["text_color"], TITLE_SIZE=p["title_size"],
        TITLE_WEIGHT=p["title_weight"], LIGHT_SIZE=light_size, LIGHT_WEIGHT=p["light_weight"],
        SUB_TOP=p["sub_top"], SUB_BOTTOM=sub_bottom, SUB_V1=round(100 * sub_bottom / h, 1),
        SUB_MAX_V=int(SUB_MAX_V * 100), SUB_SIZE=p["sub_size"], SUB_WEIGHT=p["sub_weight"],
        LS=p["sub_ls"], SUB_COLOR=sub_color, TITLE_SPANS=spans,
        SUB_TEXT=html.escape(p["sub"]),
        META_ONE=f"canvas {w}x{h} · D50 · {p['title']}/{p['sub']}",
    )
    return HTML_TEMPLATE.substitute(t), meta


def geometry_warnings(meta):
    """安全区几何守卫：返回 [(级别, 文案)]，FAIL 级由 qc 兜底判定。"""
    w, h = meta["canvas"]
    out = []
    est_w = sum(round(len(s) * (meta["title_size"] if i % 2 == 0
                                else meta["title_size"] * meta["light_ratio"]))
                for i, s in enumerate(meta["title"].split()))
    est_w += meta["gap"] * (len(meta["title"].split()) - 1)
    checks = [
        ("标题块顶低于安全区上沿", meta["title_top"] >= SAFE["v_lo"] * h),
        ("标题块底越过安全区下沿", meta["title_bottom"] <= SAFE["v_hi"] * h),
        ("小字块底越过安全区下沿", meta["sub_bottom"] <= SAFE["v_hi"] * h),
        (f"小字块底越过 {int(SUB_MAX_V*100)}% 角标避让线", meta["sub_bottom"] <= SUB_MAX_V * h),
        ("标题估算宽度越出水平安全区", est_w <= (SAFE["h_hi"] - SAFE["h_lo"]) * w),
        ("主字号低于画布高 8% 可读下限", meta["title_size"] >= 0.08 * h),
    ]
    for name, ok in checks:
        if not ok:
            out.append(("WARN", f"几何守卫：{name}"))
    return out


def cmd_render(args):
    w, h = parse_size(args.size)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    bg = Path(args.bg) if args.bg else out / f"bg_{w}x{h}.png"
    if not bg.exists():
        raise SystemExit(f"背景图不存在: {bg}（先跑 prep-bg 或 --bg 指定）")
    if bg.parent != out:
        shutil.copy2(bg, out / bg.name)
        bg = out / bg.name
    p = dict(canvas=(w, h), title=args.title, sub=args.sub,
             title_top=args.title_top, title_size=args.title_size,
             title_weight=args.title_weight, light_ratio=args.light_ratio,
             light_weight=args.light_weight, gap=args.gap,
             sub_top=args.sub_top, sub_size=args.sub_size, sub_weight=args.sub_weight,
             sub_ls=args.sub_ls, sub_alpha=args.sub_alpha, text_color=args.text_color,
             font=args.font, bg_fallback=args.bg_fallback,
             yavg_min=args.yavg_min, jpg_max_mb=args.jpg_max_mb)
    html_text, meta = build_html(p, bg.name)
    html_path = out / "cover.html"
    html_path.write_text(html_text, encoding="utf-8")
    (out / "cover.meta.json").write_text(
        json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")

    png = out / f"cover_{w}x{h}.png"
    chrome = find_chrome()
    run([chrome, "--headless=new", "--disable-gpu", "--hide-scrollbars",
         f"--window-size={w},{h}", "--virtual-time-budget=3000",
         f"--screenshot={png}", f"file://{html_path.resolve()}"])
    pw, ph = probe(png)
    if (pw, ph) != (w, h):
        raise SystemExit(f"截图尺寸 {pw}x{ph} ≠ {w}x{h}（查字体加载/滚动条/缩放）")

    jpg = out / f"cover_{w}x{h}.jpg"
    max_bytes = int(meta["jpg_max_mb"] * 1024 * 1024)
    for q in range(2, 8):
        run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(png),
             "-q:v", str(q), str(jpg)])
        if jpg.stat().st_size <= max_bytes:
            break
    size_mb = jpg.stat().st_size / 1048576
    flag = "✓" if size_mb <= meta["jpg_max_mb"] else "⚠"
    print(f"{flag} render: {png.name} ({w}x{h}) + {jpg.name} ({size_mb:.2f}MB)")
    for lvl, msg in geometry_warnings(meta):
        print(f"  {lvl} {msg}")


# ── previews ──────────────────────────────────────────────────────────────────
def cmd_previews(args):
    d = Path(args.dir)
    meta = json.loads((d / "cover.meta.json").read_text(encoding="utf-8")) \
        if (d / "cover.meta.json").exists() else {}
    w, h = meta.get("canvas", list(CANVAS))
    cover = Path(args.cover) if args.cover else d / f"cover_{w}x{h}.png"
    cw, ch = probe(cover)
    if (cw, ch) != (w, h):
        raise SystemExit(f"封面尺寸 {cw}x{ch} ≠ 期望 {w}x{h}")
    pv = d / "previews"
    pv.mkdir(exist_ok=True)
    made = []
    # 电脑端全入口 16:9：居中裁上下
    h169 = round(w * 9 / 16)
    pc = pv / "pc_16x9.png"
    ffmpeg_crop_scale(cover, pc, w, h169)
    made.append((pc, w, h169))
    # App 首页双列 ≈1.38:1 与保守 4:3：居中裁左右
    for ratio, name in zip(PREVIEW_RATIOS[1:], ("app_138.png", "app_43.png")):
        wr = round(h * ratio)
        f = pv / name
        ffmpeg_crop_scale(cover, f, wr, h)
        made.append((f, wr, h))
    # 手机信息流缩略图（自 16:9 裁切缩放）
    thumb = pv / "thumb_384.png"
    run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(pc),
         "-vf", "scale=384:216:flags=lanczos", "-frames:v", "1", str(thumb)])
    made.append((thumb, 384, 216))
    print(f"✓ previews: {len(made)} 件 → {pv}/")
    for f, fw, fh in made:
        pw, ph = probe(f)
        if (pw, ph) != (fw, fh):
            raise SystemExit(f"{f.name} 尺寸 {pw}x{ph} ≠ 契约 {fw}x{fh}")


# ── qc ────────────────────────────────────────────────────────────────────────
def region_yavg(bg_path, x, y, w, h):
    """ffmpeg signalstats 测区域平均亮度 YAVG（文字压深色字的对比度前提）。"""
    r = subprocess.run(
        ["ffmpeg", "-hide_banner", "-i", str(bg_path),
         "-vf", f"crop={w}:{h}:{x}:{y},signalstats,metadata=print", "-f", "null", "-"],
        capture_output=True, text=True)
    vals = re.findall(r"signalstats\.YAVG=([\d.]+)", r.stderr)
    if not vals:
        return None
    return float(vals[-1])


def cmd_qc(args):
    d = Path(args.dir)
    meta_path = d / "cover.meta.json"
    if not meta_path.exists():
        raise SystemExit(f"缺 {meta_path}（应由 render 生成；旧产物请补跑 render）")
    meta = json.loads(meta_path.read_text(encoding="utf-8"))
    w, h = meta["canvas"]
    fails, warns = [], []
    # 1) 尺寸断言
    expects = [
        (d / f"cover_{w}x{h}.png", (w, h)),
        (d / f"bg_{w}x{h}.png", (w, h)),
        (d / "previews/pc_16x9.png", (w, round(w * 9 / 16))),
        (d / "previews/thumb_384.png", (384, 216)),
        (d / "previews/app_138.png", (round(h * 1.38), h)),
        (d / "previews/app_43.png", (round(h * 4 / 3), h)),
    ]
    for f, exp in expects:
        got = probe(f) if f.exists() else (0, 0)
        if not f.exists() or got != exp:
            fails.append(f"{f.name}: {got} ≠ 契约 {exp[0]}x{exp[1]}")
        else:
            print(f"  ✓ {f.name} {got[0]}x{got[1]}")
    # 2) JPG 体积
    jpg = d / f"cover_{w}x{h}.jpg"
    if jpg.exists():
        mb = jpg.stat().st_size / 1048576
        if mb > meta["jpg_max_mb"]:
            warns.append(f"JPG {mb:.2f}MB 超过 {meta['jpg_max_mb']}MB 上传稳妥线")
        else:
            print(f"  ✓ cover jpg {mb:.2f}MB ≤ {meta['jpg_max_mb']}MB")
    else:
        warns.append("缺 JPG 上传版")
    # 3) 几何安全区守卫
    for lvl, msg in geometry_warnings(meta):
        (warns if lvl == "WARN" else fails).append(msg)
    # 4) 标题区背景亮度（深色字可读前提）
    bg = d / meta.get("bg", f"bg_{w}x{h}.png")
    if bg.exists():
        x0, x1 = round(w * SAFE["h_lo"]), round(w * SAFE["h_hi"])
        y0 = meta["title_top"]
        y1 = meta["title_bottom"]
        yavg = region_yavg(bg, x0, y0, x1 - x0, y1 - y0)
        if yavg is None:
            warns.append("YAVG 未测得（signalstats 解析失败）")
        elif yavg < meta["yavg_min"]:
            warns.append(f"标题区背景 YAVG={yavg:.1f} < {meta['yavg_min']}（深底风险，深色字对比不足）")
        else:
            print(f"  ✓ 标题区背景 YAVG={yavg:.1f} ≥ {meta['yavg_min']}")
    # 5) 汇总（机器可读 + 退出码）
    report = {"pass": not fails, "fails": fails, "warns": warns, "meta": meta}
    (d / "cover_qc.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    for m in warns:
        print(f"  ⚠ {m}")
    if fails:
        for m in fails:
            print(f"  ✗ {m}")
        raise SystemExit(f"qc FAIL（{len(fails)} 项）→ {d}/cover_qc.json")
    print(f"✓ qc PASS（warns={len(warns)}）→ {d}/cover_qc.json")


