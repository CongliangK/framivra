"""make_cover.py · B 站投稿封面产线（收编自 voice-ime 首期封面，决策 D50，2026-09-13）

用途：把「背景图 + 大标题/小字」合成为 B 站投稿封面，并产出四端裁切预览与验证门。
固化 voice-ime/cover 全链路的实测命令与定稿参数，重跑可复现（确定性优先，零外部
Python 依赖：stdlib + ffmpeg/ffprobe + Chrome）。

规格依据（2026-09-13 调研实证，详见 templates/tech-talk/references/cover.md）：
  · 上传 16:10（推荐 1920×1200；官方下限 1146×717）；
  · 电脑端全入口 16:9 容器=居中裁上下各 5%；App 首页双列 ≈1.38:1=裁左右各 ~7%；
  · 文字安全区=水平 12%~88%、垂直 10%~80%（右下 ~18%×13% 为时长角标禁区）；
  · 主标题字高建议 ≥ 画布高 8%（缩略图 1 秒可读）。

子命令链（all = prep-bg → render → previews → qc）：
  prep-bg   原图 lanczos cover-crop 到精确画布（源<目标打印插值倍数警告后照做）
  render    生成 cover.html（模板内嵌）→ Chrome headless 截图 → PNG + JPG(≤2MB 自适应)
  previews  四端裁切预览：pc_16x9 / thumb_384 / app_138 / app_43
  qc        验证门：尺寸断言(ffprobe) + 安全区几何守卫 + 标题区背景亮度(YAVG≥115) + JPG 体积

用法示例：
  python3 make_cover.py all --out <项目>/cover --bg-src <imgen原图.png> \\
      --title "说话 就是 打字" --sub "Linux 开源 · 语音键盘同引擎"
  python3 make_cover.py render --out <项目>/cover --title "…" --sub "…"   # bg 已就位时
  python3 make_cover.py previews --dir <项目>/cover
  python3 make_cover.py qc --dir <项目>/cover

大标题排版约定：--title 按空白分段，偶数段（第 1/3/5…段）用特重黑体，奇数段用细体
且字号为主字 55%（voice-ime 定稿形态：「说话 就是 打字」= 重-细-重）。

背景图生成不在本脚本内（付费动作保持人工授权）：用 imgen/ 的 GPT 系端点，命令与
提示词原则见 templates/tech-talk/references/cover.md（坑位：flare 对抽象画提示词有审核误杀记录，
优先 sunburst；sunburst 忽略 aspectRatio 出 1K 方图，prep-bg 负责裁切）。

来源项目：voice-ime/cover（决策 D50；QC 记录=该项目 COVER-REPORT.md）。
"""
