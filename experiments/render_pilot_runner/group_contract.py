def read_file(root,relative):
    return regular(root,relative).read_bytes()


def snapshot(root,identities,label):
    data={name:read_file(root,name) for name in identities}
    for name,expected in identities.items():
        require(digest(data[name])==expected,label+' changed: '+name)
    return data


def load_generator(repo):
    """Import only after all six frozen implementation files were verified.

    Import defines the original generator and its reviewed binder helpers; it
    does not call prepare, OwnedOutput, rendering, or any publication function.
    """
    spec=importlib.util.spec_from_file_location('pilot_reviewed_group_generator',Path(repo)/PREPARE)
    module=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def json_bytes(value):
    return (json.dumps(value,sort_keys=True,indent=2,allow_nan=False)+'\n').encode()


def validate_group(gp,bound,project,repo):
    implementation=snapshot(repo,IMPLEMENTATION,'Reviewed group implementation')
    spec=json.loads(implementation[SPEC])
    pinned_inputs=spec['bound_payload']
    require(len(pinned_inputs)==109 and len({row['path'] for row in pinned_inputs})==109,
            'Reviewed group input set is incomplete')
    require({row['path']:row['sha256'] for row in pinned_inputs}==bound['payload'],
            'Group generator source mapping differs from reviewed bound input')
    require((spec['source_commit'],spec['source_tree'])==(BASE_COMMIT,BASE_TREE),
            'Group generator source identity differs')
    payload=snapshot(Path(bound['root']),bound['payload'],'Original bound input')
    generator=load_generator(repo)
    require((generator.PAGE,generator.ADAPTER)==(PAGE,ADAPTER) and generator.MEMBERS==bound['entries'],
            'Reviewed generator interface differs')
    options,css=generator.original_options(payload)
    generated={PAGE:generator.make_page(options,css),ADAPTER:implementation[SOURCE_ADAPTER]}
    expected={
        'source_commit':BASE_COMMIT,'source_tree':BASE_TREE,'group_id':'T08_T07',
        'ordered_members':bound['entries'],'runtime_options':options,
        'width':WIDTH,'height':HEIGHT,'fps':FPS,'window_start':0,'duration':3600,
        'input_dependencies':[{'path':row['path'],'sha256':row['sha256']} for row in pinned_inputs],
        'generated_dependencies':[{'path':name,'sha256':digest(data)} for name,data in sorted(generated.items())],
        'implementation':[{'path':name,'sha256':sha} for name,sha in IMPLEMENTATION.items()],
    }
    # Exact list/object equality rejects omissions, duplicates, additional rows,
    # changed hashes, reordering and contradictory metadata, even if the caller
    # recomputes a perfectly valid self-reported content_identity.
    require(gp['content']==expected,'Group content differs from complete reviewed generator contract')
    expected_identity=digest(json_bytes(expected))
    require(gp['content_identity']==expected_identity,'Group content identity mismatch')
    require(gp['ordered_members']==[dict(m,local_frame_offset=-m['windowStart']) for m in bound['entries']],
            'Group member/local-frame contract differs')
    for name,data in generated.items():
        require(read_file(project,name)==data,'Group generated bytes differ from reviewed generator: '+name)
    snapshot(project,bound['payload'],'Copied bound input')
    # Also catch implementation drift during reconstruction; execution separately
    # checks the exact clean integrated checkout before and after the whole pair.
    snapshot(repo,IMPLEMENTATION,'Reviewed group implementation')
    return {'generator_commit':GROUP_COMMIT,'generator_tree':GROUP_TREE,
            'content_identity':expected_identity,
            'generated':{name:digest(data) for name,data in sorted(generated.items())},
            'implementation':dict(IMPLEMENTATION),'bound_payload_count':len(payload)}
